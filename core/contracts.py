def safe_filename(name: str) -> str:
    """清洗为合法文件名（与原程序 re.sub(r'[\\\\/:*?\"<>|]', '', x) 一致）。"""
    return re.sub(r'[\\/:*?"<>|]', "", str(name or "")).strip()


def industry_dir_name(rep_name: str, industry: str) -> str:
    return INDUSTRY_DIR_TEMPLATE.format(rep=safe_filename(rep_name), industry=safe_filename(industry))


def parse_code_from_filename(filename: str) -> str:
    m = CODE_IN_FILENAME_RE.search(str(filename or ""))
    return m.group(2) if m else ""


def parse_name_from_filename(filename: str) -> str:
    m = CODE_IN_FILENAME_RE.search(str(filename or ""))
    if m:
        return m.group(1).split("_")[-1].strip()
    return str(filename or "").split(".")[0].split("-")[0].strip()


def parse_year_from_yearly_filename(filename: str):
    m = re.search(r"(\d{4})年度", str(filename or ""))
    return int(m.group(1)) if m else None
